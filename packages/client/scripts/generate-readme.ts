/**
 * Rewrites the API reference in README.md and in the docs site's client page
 * from `openapi.json`, between the `api:start` and `api:end` markers, so the
 * list of methods cannot fall behind the client. Everything outside the
 * markers is hand-written.
 *
 * Descriptions are the Rust handlers' doc comments (utoipa's `summary`) with
 * the leading `GET /path` dropped: improve the comment and the README follows.
 */
import { readFileSync, writeFileSync } from 'node:fs';

type Operation = {
  operationId: string;
  tags: string[];
  summary?: string;
  description?: string;
  parameters?: { in: string; required?: boolean }[];
  requestBody?: unknown;
};

const spec: { paths: Record<string, Record<string, Operation>> } = JSON.parse(
  readFileSync(
    new URL('../../../apps/server/openapi.json', import.meta.url),
    'utf8',
  ),
);

/**
 * The doc comment's first sentence, without the route it starts with. A
 * comment that is only the route falls back to the longer description.
 */
function describe({ summary = '', description = '' }: Operation): string {
  const text =
    summary
      .replace(/^[A-Z]+ \S+\s*(?:[:—-]\s*)?/, '')
      .replace(/\s+/g, ' ')
      .trim() || description.replace(/\s+/g, ' ').trim();
  // A sentence ends at a period before a capital, so `incl.` does not end one.
  const sentence = (text.match(/^.*?[.!?](?=\s+[A-Z`]|$)/)?.[0] ?? text)
    .replace(/^\((.*)\)$/, '$1')
    .replaceAll('|', '\\|');
  return sentence.charAt(0).toUpperCase() + sentence.slice(1);
}

/** What the call takes: `{ path, query, body }`, whichever apply. */
function args(op: Operation): string {
  const parts = [];
  const params = op.parameters ?? [];
  if (params.some((p) => p.in === 'path')) parts.push('path');
  if (params.some((p) => p.in === 'query')) {
    parts.push(
      params.some((p) => p.in === 'query' && p.required) ? 'query' : 'query?',
    );
  }
  if (op.requestBody) parts.push('body');
  return parts.length ? `{ ${parts.join(', ')} }` : '';
}

const groups = new Map<string, string[]>();
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    const [resource, name] = op.operationId.split('.');
    const rows = groups.get(op.tags[0]!) ?? [];
    rows.push(
      `| \`${resource}.${name}(${args(op)})\` | \`${method.toUpperCase()} ${path}\` | ${describe(op)} |`,
    );
    groups.set(op.tags[0]!, rows);
  }
}

const reference = [...groups.keys()]
  .sort()
  .map((tag) =>
    [
      `### ${tag}`,
      '',
      '| Method | Endpoint | Description |',
      '|---|---|---|',
      ...groups.get(tag)!.sort(),
    ].join('\n'),
  )
  .join('\n\n');

/**
 * Replaces what sits between `start` and `end` in `file`. MDX has no HTML
 * comments, so the docs page marks the region with JSX comments instead.
 */
/** `--check` compares instead of writing, so CI never races a build. */
const CHECK = process.argv.includes('--check');

function inject(
  file: URL,
  start: string,
  end: string,
  note: string,
  body: string,
) {
  const text = readFileSync(file, 'utf8');
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (from === -1 || to < from) {
    throw new Error(`${file.pathname} needs ${start} and ${end} markers`);
  }
  const next = `${text.slice(0, from + start.length)}\n${note}\n\n${body}\n\n${text.slice(to)}`;
  if (!CHECK) {
    writeFileSync(file, next);
  } else if (next !== text) {
    console.error(`${file.pathname} is stale: run \`pnpm generate\``);
    process.exitCode = 1;
  }
}

inject(
  new URL('../README.md', import.meta.url),
  '<!-- api:start -->',
  '<!-- api:end -->',
  '<!-- Generated by `pnpm generate` from openapi.json. Do not edit by hand. -->',
  reference,
);

// MDX reads `{` and `<` outside code as JSX.
inject(
  new URL('../../../apps/docs/content/sdks/client.mdx', import.meta.url),
  '{/* api:start */}',
  '{/* api:end */}',
  '{/* Generated by `pnpm --filter @rustrak/client generate` from openapi.json. Do not edit by hand. */}',
  reference.replace(/(`[^`]*`)|[{}<]/g, (match, code) =>
    code ? code : `\\${match}`,
  ),
);
